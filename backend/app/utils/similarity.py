"""任务标题相似度判定（「生成任务」去重与重复任务清理共用一份实现）。

## 为什么要单独抽一个模块
``POST /task/generate`` 的服务端去重与 ``scripts/cleanup_duplicate_tasks.py``
的清理判定必须是**同一套口径**：如果各写一份，一边改了阈值/停用词、另一边没改，
就会出现"接口认为不重复、脚本认为是重复"的自相矛盾（脚本会把接口刚生成的任务删掉，
或者接口继续塞脚本会删的重复任务）。所以只留这一份实现，两边都 import 它。

## 为什么是 bigram Jaccard（而不是分词、编辑距离）
- **中文没有空格**，按词比就得引入分词（本项目依赖清单里没有 jieba，也不该为一次去重
  背一个词典）；字符 bigram 是"零依赖 + 对中文够用"的折中。
- bigram 对"换个说法"足够敏感：重复生成的同题任务差异通常只是语序、量词、时间词
  （「用 3 天做一次技术方向小实验」vs「用三天做一次技术方向小实验」），
  字符二元组几乎完全重合；而不同主题的任务连字都对不上。
- Jaccard（交集 / 并集）天然处理"长短不一"：并集把多出来的字算进分母，
  所以"往里塞字凑相似"反而会拉低分数，比"交集 / 较短串长度"更难被绕过。

## 为什么需要停用词表
重复任务之间的差异**恰好落在这些词上**：模型重复生成时爱换「写/做」「一个/两个」
「3 天/一天」以及交付物泛称（「小工具」「项目」「任务」）。不丢这些词，
同题对会被这些噪音稀释到阈值以下（漏判），所以归一化时统一丢掉。

⚠️ 停用词表**只收语气词、量词、时间词、交付物泛称**，绝不收主题词
（Java、命令行、通讯录、简历、面试…）：一旦把主题词也丢掉，
「用 Java 写命令行工具」和「用 C 写命令行工具」会被压成同一个串，变成误判。
保守原则是**宁可漏判，不可误判** —— 漏判只是少去重一次，误判会让用户再也拿不到新任务。

## 为什么单靠 Jaccard 不够（2026 现场漏网案例）
用户连点两次生成任务，库里出现两条：
「用 Java 做一个健身打卡命令行小工具」/「用 Java 做一个健身动作计数器命令行小工具」。
两条**讲的是同一件事**（Java + 健身 + 命令行工具，只是一条叫"打卡"、一条叫"动作计数器"），
但 bigram Jaccard 只有 **0.438**，低于原来的 0.6，于是被放行、塞进了两条。
原因：这种"长标题中间换一个词"的重复，加了一个词就新增一整串 bigram 到并集里，
Jaccard 被稀释到 0.4~0.5 区间，而这个区间**恰好与"真的不同任务"重叠**（实测
「用 3 天做一次职业方向小实验」vs「…技术方向…」= 0.400），所以**单靠下调阈值无解**：
把阈值降到 0.438 以下，职业/技术那一对（0.400）也会被合并。

## 判定规则：A 组（Jaccard 粗筛 + 最长公共子串细筛）与 B 组（包含判定）取其一，
## 再 + 一条"主题/语言对不上"的否决（都是实测选出来的）
1. ``similarity(normalize(a), normalize(b)) >= CANDIDATE_SIMILARITY_THRESHOLD``（0.43）
   —— 粗筛，"像同一件事"。选 0.43 是因为它**只比实测的漏网案例（0.438）低一点点**，
   同时高于最大的一对"不同任务"（0.400），是实测数据给出的最窄可行区间；
2. ``longest_common_substring(normalize(a), normalize(b)) >= MIN_COMMON_SUBSTRING``（6）
   —— 细筛，"是同一件事、只是某个词说法不同"。**这一条才是关键**：
   同题重复会留下一条很长的连续公共片段，而"换主题词"的不同任务只剩短短一截。
   ⚠️ 实测修正：漏网案例的最长公共子串是 **6 字**（``'Java健身'``），**不是**当初手工估的
   "≥8 字"。因为 ``normalize()`` 会把「命令行/小工具/做/一个」这些词整段抽掉，
   连续片段被切断。所以门槛取 6（职业/技术要求误判的那一对只有 4 字 ``'方向实验'``）。
   反过来的证据：仅当"职业↔技术"这**一个词**不同、语序完全一致时（两边归一化后
   只差 2 个字），LCS 这一刀切不出来 —— 但那时 Jaccard 是 0.556，被条件 1 挡住，
   两条条件在实测数据上互补，缺任何一条都会漏判或误判；
2.5. **包含判定（``is_contained_title``）**：归一化后较短的那条**整个是**较长那条的
    **连续子串**（``short in long``）且短的那条长度 ``>= MIN_CONTAINMENT_LENGTH``（4）
    —— 满足它时**直接算通过条件 1/2 这一关**（不必再凑 Jaccard / LCS）。
    为什么补这一条：条件 2 的门槛是"绝对值 6 字"，这对长标题合适，但 ``normalize()``
    会把「小工具 / 命令行 / 做 / 一个」整段抽掉，**短标题归一化后本来就只剩 4~5 个字**，
    在数学上永远达不到 6，于是「做一个健身打卡小工具」与它自己、与「做一个健身打卡工具」
    全被判为**不重复**（实测 Jaccard 1.000 / 0.600、LCS 都只有 4，被条件 2 放行）——
    这是 2026 现场漏网的真 bug（同一个痛点连点两次能攒出两条字面几乎一样的任务）。
    为什么用"包含"而不是继续调条件 2 的门槛：包含关系恰好就是"同一件事、只是其中一个
    说法更啰嗦"的形态，判据精确；而把 ``MIN_COMMON_SUBSTRING`` 从 6 降到 4 会重新打开
    上一轮刚堵掉的误合并 —— 实测「用 3 天做一次技术方向小实验」vs「…职业方向…」的
    LCS 正好是 **4**（``'方向实验'``），门槛一降到 4 这一对立刻变成重复，而那属于用户
    明确"绝不能合并"的对。包含判定不会误伤这类：它们**共享**一段但互不包含，讲的是两件事。
    包含判定本身也**不是**无边界的松口子，它被 ``MIN_CONTAINMENT_LENGTH`` 与条件 3
    两道限制夹住：
    - 下限 4 字：实测最短的重复标题就是 4 字（``'健身打卡'``），再往下降会把
      「技术」「健身」这种 2 字词从"共享一小段"变成"包含"；
    - 条件 3 保护词仍然否决：否则短标题会顺带把**换了主题**的长标题也吞掉（主题词只出现在
      一侧即冲突，语义本轮未动）。（注意"包含路"也**不是**独立的第四种否决：它只在保护词
      不冲突时才算数，因为保护词否决是最后一道、对所有路都生效。）
    ⚠️ 已知代价（实测，如实记录）：包含路会让**短标题**不再需要凑条件 1/2，所以它的边界比
    条件 2 宽。真实库里两个"健身"任务（admin：「做一个健身打卡小工具」/「做一个健身动作计数
    小工具」）**不受影响**：归一化后是 ``'健身打卡'`` 与 ``'健身动作计数'``，共享的只有
    ``'健身'``，前者**不是**后者的子串（实测 contained=False），改后仍不合并。
    ⚠️ 语义放宽史（本模块第二轮改动，用户 2026 拍板）：包含路认出「做一个健身打卡小工具」vs
    「用 Java 做一个健身打卡命令行小工具」（contained=True）之后，曾被条件 3 的**旧语义**
    （语言名与主题词混在一张表、共用"只在一侧出现 ⇒ 冲突"）否决成 ``is_similar=False`` ——
    因为 ``'Java'`` 只出现在长标题那一侧。用户决定 **"带不带语言前缀不算两件事"**，
    于是本轮把保护词**按语义拆成两组**，只放宽语言名那组：一侧没提语言 ⇒ 不算冲突，
    这一对现在合并（详见条件 3 的常量注释与 :func:`has_conflicting_protected_token`）。
    主题词那一组的语义**一个字没动**。
    （顺带记录一次失败的尝试：为"挡"这对而给保护词表加子串型保护词是**行不通**的，
    见条件 3 常量注释里的实测。）
3. ``has_conflicting_protected_token()`` 必须为假 —— 阈值/子串两条都属于**长度型**
   判据，挡不住"长度不变、只换关键名词"：
   「用 Java 做一个健身打卡命令行小工具」vs「用 C 语言做一个健身打卡命令行小工具」
   实测 Jaccard=0.462、LCS=7，**两条都会通过**，但"用 Java 做"和"用 C 做"是两件任务。
   所以再补一条硬约束。⚠️ 这条约束**对语言名与主题词必须是两种不同的语义**，故本模块把
   保护词拆成 ``PROTECTED_LANGUAGE_TOKENS`` / ``PROTECTED_TOPIC_TOKENS`` 两组：
   - **主题词**（健身 / 记账 / 通讯录 / 简历 / 面试 / 职业 / 技术）：**只出现在一侧 ⇒ 冲突**
     （原语义，本轮未动）；
   - **语言名**（Java / Python / C++ / C# / C / Go / JS / TS / Rust / Kotlin）：
     **只有两边都提到了语言、且两边没有共同语言 ⇒ 冲突**（本轮放宽）——一侧没提语言
     不算冲突（"带不带语言前缀不算两件事"），有共同语言也不算冲突（只是说法更全）。
     ⇒「做一个健身打卡小工具」与「用 Java 做一个健身打卡命令行小工具」现在**合并**
     （这一对原先被旧语义拦下，是本轮唯一有意放开的行为）；
     「用 Java 做…」vs「用 C 语言做…」仍是冲突（两边都有语言且无交集）。

四条合起来的效果：真实的「长标题换个词」重复仍走条件 1+2，短标题重复走条件 2.5，
"主题不同 / 语言不同"仍被条件 3 挡下；上一轮已确认必须放行的「职业方向 / 技术方向」不受影响
（它既不过条件 1，也不构成包含，主题词还额外兜一层）。
"""

from __future__ import annotations

import re
from typing import Iterable, Tuple

# 归一化时丢掉的词：它们在重复任务之间恰好是差异所在
# （「写一个命令行小工具」vs「做一个命令行小工具，3 天摸清方向」）。
# 只收虚词/量词/时间词/交付物泛称，**不收主题词**（见模块 docstring 的警告）。
STOP_WORDS: Tuple[str, ...] = (
    "一个", "两个", "能演示的", "摸清方向", "小工具", "项目", "任务", "天", "并",
    "做", "写", "用", "的", "能", "小",
)

# ---------------------------------------------------------------------------
# 判定规则（常规路 1∧2，或包含路 2.5，再 ∧ 非 3；详见模块 docstring 的推导过程）
# ---------------------------------------------------------------------------

# 条件 1：bigram Jaccard 的**粗筛**阈值。
# 原值是 0.6，前提是"同题对 0.8~1.0、不同题 <0.3"；但现场漏网案例（「健身打卡」/
# 「健身动作计数器」）实测只有 0.438 —— 长标题换一个词会把 Jaccard 稀释到 0.4~0.5，
# 而这个区间与"真的不同任务"（职业方向/技术方向 = 0.400）重叠，所以单靠降阈值必然误杀。
# 0.43 是实测出来的最窄可行值：≥ 漏网案例的 0.438 做不到（0.438 > 0.43 才刚好过），
# 只比它低 0.008，同时比最大的"不同任务"0.400 高 0.03，两边都留了隔离带。
# ⚠️ 这个值本身**不足以**判定重复，必须同时满足 MIN_COMMON_SUBSTRING 与
#    PROTECTED_*_TOKENS 那条否决 —— 单独把本值当判定阈值用会误杀（见模块 docstring）。
CANDIDATE_SIMILARITY_THRESHOLD = 0.43

# 条件 2：归一化后**最长公共子串**（连续片段）的最小长度。
# 含义："同一件事换个说法"会留下一条很长的连续公共片段（「技术方向小实验」= 8 字、
# 「Java健身」= 6 字），而"换了主题词"的不同任务只剩短短一截
# （「方向实验」= 4 字、「命令行小工具」被停用词切碎后 = 4 字）。
# 取 6 的理由：实测同题对最低是 6（漏网案例），必须不同任务最高是 4，中间没有样本，
# 取 6 等于"贴着同题对的下界"，两边各留 2 字余量。
# ⚠️ 别写成 8：漏网案例只有 6 字（`normalize()` 把「命令行/小工具/做/一个」抽掉，
#    连续片段被切断），门槛 8 会把这条真实漏网案例重新漏掉（实测已验证）。
MIN_COMMON_SUBSTRING = 6

# 条件 2.5（包含判定）：归一化后**较短那条**自身作为一个连续子串出现所需的最小长度。
# 含义："短标题整个被长标题包含"= 同一件事、只是其中一个说法更啰嗦（只是多了限定词/交付物名），
# 这是 short in long 能表达、而"最长公共子串 >=6"表达不了的一类重复：
# normalize() 会把停用词整段抽掉，短标题归一化后本来就只剩 4~5 个字，永远凑不满 6。
# 取 4 的理由：实测最短的重复标题就是 4 字（'健身打卡'）；再往下降（3/2）会把「技术」
# 「健身」这种主题词从"共享一小段"变成"包含"，那是误判方向。
# ⚠️ 本条件**不能**用"把 MIN_COMMON_SUBSTRING 调低"来替代：降到 4 会让 LCS=4 的
#    「职业方向 / 技术方向」这一对真不同任务变成重复（实测，用户明确要求绝不能合并）。
MIN_CONTAINMENT_LENGTH = 4

# ---------------------------------------------------------------------------
# 条件 3：**硬保护词** —— ⚠️ 本轮把原来混在一起的 PROTECTED_TOKENS 按语义拆成
# 「语言名」与「主题词」两组，**两组语义不同**（这是本模块唯一的语义放宽）。
# ---------------------------------------------------------------------------
# ## 为什么必须拆成两组（而不是继续共用"只在一侧出现 ⇒ 冲突"）
# 旧实现把两类词混在一张表里，共用同一条语义。该语义**对主题词成立、对语言名不成立**：
# 语言只是"用什么做"的**实现前缀**，不是"要做什么"。用户 2026 拍板：
# **"带不带语言前缀"不算两件事** ——
#   「做一个健身打卡小工具」与「用 Java 做一个健身打卡命令行小工具」讲的是同一件事，
#   旧语义却因为 'Java' 只在长标题一侧而判冲突（实测包含路已认出 contained=True，
#   最终仍 is_similar=False）。主题词恰恰相反：「健身」vs「跑步」、「技术」vs「职业」
#   换了就是两件不同的任务，**不能**跟着放宽（用户点名的
#   「用 3 天做一次技术方向小实验 / 职业方向小实验」必须永远不合并）。
# 一条语义表达不了这两种需求，所以按语义拆开；主题词那组本轮**一个字都没动**。
#
# ## 【语言名】新语义：只有**两边都提到了语言、且两边没有共同语言**才算冲突
#   「用 Java 做…」vs「做一个…」              -> 一侧没提语言     -> 不冲突（本轮放开的正是这种）
#   「用 Java 做…」vs「用 C 语言做…」          -> 都有、无交集     -> 冲突（仍是两件任务）
#   「用 Java 做…」vs「用 Java 和 Python 做…」 -> 都有、有交集     -> 不冲突（同一件事、说法更全）
# 即 ``langs_a and langs_b and langs_a.isdisjoint(langs_b)``。
# 依据：**多提**一个语言前缀不改变"要做什么"（同一件事的冗余描述），
#       而两边提了**不同**语言才真的改变了要做的东西。
#
# ## 🔧 子串坑（上一轮踩过，这轮必须绕开）：语言名要按**独立词/词边界**匹配
# 语言名里存在**真子串对**：'C' ⊂ 'C++' / 'C#'，'Java' ⊂ 'JavaScript' 同理。
# 裸子串匹配会让「用 C 做…」与「用 C++ 做…」两边都被认成"提到了 C" ⇒ 不冲突 ⇒
# **误合并**（实测改前 is_similar=True，改后必须是 False）。所以语言名一律走
# :data:`_LANGUAGE_PATTERNS` 的**词边界**正则：匹配位置的左右都不能紧贴
# ``[A-Za-z0-9_+#]``，于是 'C' 不会命中 'C++'/'C#'，'Java' 不会命中 'JavaScript'，
# 'Go' 不会命中 'Google'。**不能**只做 ``"C" in text`` 这种裸子串判断。
# （同族教训，第二次踩：当初为挡「健身打卡 / 健身动作计数」而往保护词里加「健身动作」
#  也行不通 —— 「健身动作」本身是「健身动作计数」的子串，加进去立刻让原本必拦的
#  「健身动作计数 / 健身动作计数器」退化成"保护词冲突"而**不再合并**，实测。故主题词表不加词。）
#
# ## 【主题词】语义保持原样（**本轮未动，也不要顺手改**）
# 仍用"该词是否只出现在一侧"，比对对象仍是**归一化串**（原实现即如此）：
# 中文没有词边界、主题词都是 2 字实词，且该组内部不存在互为子串的词对，
# 所以裸子串就是它原本（也是用户冻结）的语义。
# 入选标准（很窄，不要随手加词）：把「X Y」换成「X Z」之后"做的事"必然不同；
# 而换说法/换量词/加时间词（打卡→打卡记录、一个→两个、加"两天"）仍是同一件事，
# 那些词**绝不能**进这张表（否则会把该合并的对又拆开）。与 STOP_WORDS 不重叠。
PROTECTED_LANGUAGE_TOKENS: Tuple[str, ...] = (
    "Java", "Python", "C++", "C#", "C", "Go", "JS", "TS", "Rust", "Kotlin",
)

# 真实库里出现过的"换掉就不是同一件事"的业务主题词；后三个里「职业 / 技术」是
# 「职业方向 / 技术方向」这一对真不同任务的关键词：它们同时被 Jaccard=0.400 < 0.43 挡住
# （两道保险），列在这里是为了防守语序变化后 Jaccard 升上来
# （实测"职业/学业"同构对 Jaccard=0.556 会过条件 1，靠本表才不误判）。
PROTECTED_TOPIC_TOKENS: Tuple[str, ...] = (
    "健身", "记账", "通讯录", "简历", "面试", "职业", "技术",
)

# 语言名词边界正则用到的"紧贴字符"集合（见上面「子串坑」）：
# 字母/数字/下划线（词内字符）+ 加号/井号（C++ / C# 的尾巴）。
_LANGUAGE_BOUNDARY = r"[A-Za-z0-9_+#]"


def _language_pattern(token: str) -> re.Pattern:
    return re.compile(rf"(?<!{_LANGUAGE_BOUNDARY}){re.escape(token)}(?!{_LANGUAGE_BOUNDARY})")


# 预编译：PROTECTED_LANGUAGE_TOKENS 在进程内是常量，没必要每次判定都编译正则。
_LANGUAGE_PATTERNS: Tuple[Tuple[str, re.Pattern], ...] = tuple(
    (token, _language_pattern(token)) for token in PROTECTED_LANGUAGE_TOKENS
)



def normalize(title: str) -> str:
    """把标题压成"只保留主题词"的形式，用来做相似度比较。

    三步：去掉空白与标点 -> 去掉数字（「3 天」/「三天」要能对齐）-> 去掉停用词。
    """
    text = re.sub(r"[\s\W_]+", "", title or "", flags=re.UNICODE)
    text = re.sub(r"[0-9]+", "", text)
    for word in STOP_WORDS:
        text = text.replace(word, "")
    return text


def bigrams(text: str) -> set:
    """字符 bigram 集合；长度不足 2 时退化成单元素集合（保留原串，避免空集）。"""
    return {text[i : i + 2] for i in range(len(text) - 1)} or {text}


def similarity(a: str, b: str) -> float:
    """bigram Jaccard 相似度，取值 0~1。

    ⚠️ 入参必须是 :func:`normalize` 之后的串（本函数不再归一化）——
    调用方各自归一化，是为了让"归一化后的 key"能复用（脚本按 key 分桶）。
    ⚠️ 本函数只是**判定用的第一个条件**，单独拿它跟阈值比会误判：
    完整判定请用 :func:`is_similar`（它还要看最长公共子串与保护词）。
    """
    ga, gb = bigrams(a), bigrams(b)
    if not ga or not gb:
        return 0.0
    return len(ga & gb) / len(ga | gb)


def longest_common_substring(a: str, b: str) -> str:
    """两串的**最长公共连续子串**（不是子序列）——"最长公共子串"的标准 DP 解法。

    为什么是"连续"而不是"公共子序列"：子序列允许跳着取字，任意两句话都能凑出很长的
    公共子序列（「用 Java 做健身工具」与「用 C 做记账工具」能凑出"用做工具"），
    那就挡不住"只换了主题词"的误判。连续片段才能表达"整段讲的是同一件事"。

    复杂度 O(len(a) * len(b))，只保留上一行（标题几十字，开销可忽略）。
    """
    if not a or not b:
        return ""
    previous = [0] * (len(b) + 1)
    best_length = 0
    best_end = 0  # a 中公共子串的结束下标（不含）
    for i, char_a in enumerate(a, start=1):
        current = [0] * (len(b) + 1)
        for j, char_b in enumerate(b, start=1):
            if char_a == char_b:
                current[j] = previous[j - 1] + 1
                if current[j] > best_length:
                    best_length = current[j]
                    best_end = i
        previous = current
    return a[best_end - best_length : best_end]


def is_contained_title(a: str, b: str) -> bool:
    """条件 2.5：归一化后**较短的那条整个是**较长那条的连续子串（``a``/``b`` 必须是归一化串）。

    为什么用"包含"这条路（而不是继续调 LCS 门槛）见模块 docstring 的条件 2.5：
    短标题归一化后只有 4~5 个字，绝对门槛 6 在数学上不可达；而"包含"恰好是
    "同一件事、一个说法更啰嗦"的形态，且**不会**误伤"共享一小段但讲的是两件事"的标题
    （那种标题互不包含，例如「技术方向实验」与「职业方向实验」）。

    两个边界：
    - **下限 ``MIN_CONTAINMENT_LENGTH``**：太短的串（2~3 字）做子串没有判别力；
    - **两侧都必须非空**：空串是任何串的子串，但空串意味着"归一化后什么都不剩"
      （标题只由停用词组成），拿它去跟别的标题比是纯噪音，直接返回 False。
    """
    shorter, longer = (a, b) if len(a) <= len(b) else (b, a)
    if len(shorter) < MIN_CONTAINMENT_LENGTH:
        return False
    return bool(longer) and shorter in longer


def extract_languages(title: str) -> frozenset:
    """从**原始标题**里按**词边界**抽出提到的语言名（条件 3 的语言名一路用）。

    为什么吃原始标题、而不是归一化串：``normalize()`` 会去掉 ``+``/``#`` 等非字母字符，
    ``'C++'``/``'C#'`` 会被压成 ``'C'``，语言名之间要区分的差别当场丢失。
    为什么用词边界而不是裸子串：见条件 3 常量注释的「子串坑」（'C' ⊂ 'C++'/'C#'）。
    """
    text = title or ""
    return frozenset(token for token, pattern in _LANGUAGE_PATTERNS if pattern.search(text))


def has_conflicting_protected_token(a: str, b: str) -> bool:
    """条件 3：保护词是否**冲突**（``a``/``b`` 是**原始标题**，本函数内部自行归一化）。

    ⚠️ 入参语义本轮变过：以前要求传"归一化后的 key"、且语言名与主题词共用一条
    "只在一侧出现 ⇒ 冲突"。现在改吃**原始标题**（:func:`is_similar` 直接传它收到的
    ``a``/``b``）—— 因为语言名必须回到原始文本才分得清 ``'C'`` / ``'C++'`` / ``'C#'``
    （归一化会把后两者压成 ``'C'``）。两组词各自的新语义：
    - **主题词**：只出现在一侧 ⇒ 冲突（原语义，本轮未动）；
    - **语言名**：两侧都提到语言、且没有共同语言 ⇒ 冲突（本轮放宽；一侧没提语言不算冲突）。
    """
    key_a, key_b = normalize(a), normalize(b)
    # 主题词：原语义 —— 裸子串、在归一化串上比（该组内部没有互为子串的词对，见常量注释）。
    for token in PROTECTED_TOPIC_TOKENS:
        if (token in key_a) != (token in key_b):
            return True
    # 语言名：新语义 —— 一侧没说语言就不算冲突（"带不带语言前缀不算两件事"），
    # 两侧都说了、但不是同一个语言才算冲突；有共同语言说明只是说法更全，不算冲突。
    languages_a = extract_languages(a)
    languages_b = extract_languages(b)
    return bool(languages_a) and bool(languages_b) and languages_a.isdisjoint(languages_b)


def is_similar(a: str, b: str, threshold: float = CANDIDATE_SIMILARITY_THRESHOLD) -> bool:
    """两个标题（``a``/``b`` 可以是**原始标题**）是否同题 —— 唯一的对外判定入口。

    ``POST /task/generate`` 的去重与 ``cleanup_duplicate_tasks.py`` 的清理都必须走这里，
    保证两边口径完全一致。因为要接受原始标题，本函数**自己做归一化**（这也是它跟
    :func:`similarity` / :func:`longest_common_substring` 这两个"只吃归一化串"的
    底层件的区别）。

    判定 = ［条件 1（Jaccard 粗筛）∧ 条件 2（最长公共子串细筛）］
           或 条件 2.5（包含判定：短标题整个是长标题的连续子串）
           ∧ 非条件 3（保护词否决：主题词"只在一侧即冲突" ∨ 语言名"两侧都有且无共同语言即冲突"）。
    各条的含义与选值依据见模块 docstring 与各常量的注释。

    ⚠️ 语义变更史（都在模块 docstring 里）：原先是"Jaccard >= threshold"一条；后来加条件 2
    是为了堵住"长标题中间换一个词"的真实重复（0.438 < 0.6），而单把阈值降到 0.438 又会误杀
    「职业方向 / 技术方向」这种只差一个词的真不同任务；再加条件 2.5 是为了堵住**短标题**
    永远达不到绝对门槛 6 的数学漏洞（「做一个健身打卡小工具」与它自己都判不重复）；
    本轮（用户拍板"带不带语言前缀不算两件事"）只放宽了条件 3 里的**语言名**：
    一侧没提语言不再算冲突，于是「做一个健身打卡小工具」与「用 Java 做一个健身打卡
    命令行小工具」**从"不合并"变成"合并"**（主题词语义未动，阈值/条件 1/2/2.5 均未动）。

    ``threshold`` 只覆盖**条件 1**的阈值（留参数是为了排查问题/临时试验），
    条件 2/2.5/3 是固定规则，不随它变。
    """
    key_a, key_b = normalize(a), normalize(b)
    key_contained = is_contained_title(key_a, key_b)
    # 两条路满足其一即可（见模块 docstring 条件 2.5）：
    # - 常规路：Jaccard 过粗筛 **且** 最长公共子串过细筛（"长标题换个词"的重复）；
    # - 包含路：短标题整个是长标题的子串（"短标题 vs 更啰嗦的同题"）。
    #   ⚠️ 包含路**刻意不叠加 Jaccard 门槛**：短标题 vs 长标题的 Jaccard 天然偏低
    #   （实测「做一个健身打卡小工具」在其子串形态上只有 0.143~0.300；即使是必拦的
    #   「做一个健身打卡小工具 / 做一个健身打卡工具」也"只有"0.600，靠的是包含关系
    #   而不是分数）。叠加门槛会把"短标题进长标题"这一类重新漏掉 —— 那正是"短标题
    #   永远过不了绝对阈值"这个 bug 的同一类成因。
    #   包含路的松紧由 MIN_CONTAINMENT_LENGTH 与下面的保护词否决共同控制。
    if not key_contained:
        if similarity(key_a, key_b) < threshold:
            return False
        if len(longest_common_substring(key_a, key_b)) < MIN_COMMON_SUBSTRING:
            return False
    # 条件 3 传**原始标题**（不是 key）：语言名要回到原始文本才分得清 C / C++ / C#，
    # 函数内部自己归一化（主题词仍在归一化串上比）。
    return not has_conflicting_protected_token(a, b)
