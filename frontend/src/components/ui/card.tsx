import * as React from "react"
import { cn } from "@/lib/utils"

function Card({ className, ...props }: React.ComponentProps<"div">) {
  return (
    <div
      data-slot="card"
      /*
       * 2026-10 收口：不再画可见描边 —— 与首页卡片一致，分层靠 shadow-card 的极轻扩散。
       * 刻意用 `border-transparent`（而不是删掉 border）：宽度仍是 1px，
       * 全站尺寸不会因为这次改动发生 1px 位移；打印样式（print.css）会强制成 #999 实线。
       * 新页面优先用 components/Panel.tsx（一份 20px 内边距，不用再各写 py-5/px-5）。
       */
      className={cn(
        "flex flex-col gap-6 rounded-xl border border-transparent bg-card py-6 text-card-foreground shadow-card",
        className
      )}
      {...props}
    />
  )
}

